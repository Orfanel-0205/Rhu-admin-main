function humanizeKey(key: string): string {
  return key
    .replace(/^(usr|users|sms|tm|appt|inv|rx|con|dash|evt|ev2|set|rep|an|hm|nav)_/i, "")
    .replace(/_/g, " ")
    .replace(/\b\w/g, (char) => char.toUpperCase());
}

export const t = (
  key: string,
  lang: Lang,
  params?: Record<string, string | number>
): string => {
  const resolvedKey = ALIASES[key] ?? key;
  const entry = T[resolvedKey] ?? EXTRA[key] ?? EXTRA[resolvedKey];

  let str = entry?.[lang] ?? entry?.en ?? humanizeKey(key);

  if (params) {
    for (const [paramKey, value] of Object.entries(params)) {
      str = str.split(`{${paramKey}}`).join(String(value));
    }
  }

  return str;
};
